name="Nandhini Is"
''' this returns in isalnum false as
it contain whitespace character'''
print("1",name.isalnum())#checks whether the strings are alphanumeric
print("2",name.isalpha())#checks all are alphabetic
print("3",name.isdigit())#check if string contains digit
print("4",name.istitle())#check if string's words's first letter  contains uppercases
print("5",name.isupper())#check if the string contains uppercase
print("6",name.islower())#check if the string contains lowercase
print("7",name.isspace())#check if the string contains space
print("8",name.endswith("i"))#check if the string ends with the letter "i"
print("9",name.startswith("N"))#check if the string starts with "N"